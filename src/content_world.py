def Q(sec, p, q, a, accept, voice=None, **kw):
    s = qa(q, a, accept, voice, **kw)
    s["_sec"] = sec; s["_p"] = p
    return s

def region_quiz(qid, title, full, speak, sections, steps, note):
    names = {sid: nm for sid, nm, _ in sections}
    items = []
    for i, s in enumerate(steps):
        sec, p = s.pop("_sec"), s.pop("_p")
        s["cat"] = names[sec]
        items.append({"id": str(i + 1), "label": str(i + 1), "sec": sec, "src": p, "steps": [s]})
    return {"id": qid, "file": qid + ".html", "type": "qa", "order": "random", "title": title, "full": full,
            "speakTitle": speak, "unit": "一問一答", "note": note,
            "sections": [{"id": sid, "name": nm, "pages": pg} for sid, nm, pg in sections], "items": items}

